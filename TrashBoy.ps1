# ================================================================
#  SCAN + REPORT (TOOL 1)
# ================================================================
function Invoke-UnwatchedScan {
    param([string[]]$FilterLibraries = @())

    Start-Log 'TrashBoy_Scan'

    $dataSource = if ($TautulliConfig.Enabled -and $Script:ConnectionStatus.Tautulli) {
        "Tautulli (MinWatchedPercent: $($TautulliConfig.MinWatchedPercent)%)"
    } else {
        'Plex viewCount (Tautulli disabled or unreachable)'
    }

    # ── Runtime override for MaxPlayCount ─────────────────────────────────────
    $effectiveMaxPlays = $ScanConfig.MaxPlayCount
    Write-Host ''
    Write-Host ("  Max play count threshold  [{0}] -- press Enter to accept, or type a number to override:" -f $effectiveMaxPlays) -ForegroundColor Cyan
    $overrideInput = Read-Host '  Threshold'
    if ($overrideInput.Trim() -ne '') {
        $parsed = 0
        if ([int]::TryParse($overrideInput.Trim(), [ref]$parsed) -and $parsed -ge 0) {
            $effectiveMaxPlays = $parsed
            Write-Host ("  Using override: {0}" -f $effectiveMaxPlays) -ForegroundColor Yellow
        } else {
            Write-Host ("  Invalid input -- using config default: {0}" -f $effectiveMaxPlays) -ForegroundColor Yellow
        }
    }
    # ──────────────────────────────────────────────────────────────────────────

    Write-Log ''
    Write-Log '  ============================================================' 'Cyan'
    Write-Log '   TrashBoy  |  Unwatched Media Report' 'Cyan'
    Write-Log ('   {0}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')) 'Cyan'
    Write-Log '  ============================================================' 'Cyan'
    Write-Log ''
    Write-Log ("  Play data source   : {0}" -f $dataSource) 'White'
    Write-Log ("  Max play count     : {0}{1}" -f $effectiveMaxPlays, $(if ($effectiveMaxPlays -ne $ScanConfig.MaxPlayCount) { '  (overridden from config)' } else { '' })) 'White'
    Write-Log ("  Sort by            : {0}" -f $ScanConfig.SortBy) 'White'
    Write-Log ''

    if (-not $Script:ConnectionStatus.Plex) {
        Write-Log '  Plex is not reachable. Cannot scan.' 'Red'
        return $null
    }

    # Clear Tautulli section cache for fresh scan
    $Script:TautulliCache = @{}

    Write-Log '  Discovering Plex libraries...' 'DarkGray'
    $allLibraries = Get-PlexLibraries
    if (-not $allLibraries -or $allLibraries.Count -eq 0) {
        Write-Log '  No libraries found in Plex. Check PlexConfig.' 'Red'
        return $null
    }

    foreach ($lib in $allLibraries) {
        $svc = if ($LibraryMap.ContainsKey($lib.title)) { $LibraryMap[$lib.title] } else { '(unmapped -- will skip)' }
        Write-Log ("  {0,-35} [{1}]  → {2}" -f $lib.title, $lib.type, $svc) 'DarkGray'
    }

    # Filter to mapped libraries only (unmapped = no *arr service = nothing to scan or delete)
    $mappedLibraries = $allLibraries | Where-Object { $LibraryMap.ContainsKey($_.title) }
    $skippedLibraries = @($allLibraries | Where-Object { -not $LibraryMap.ContainsKey($_.title) })
    if ($skippedLibraries.Count -gt 0) {
        Write-Log ''
        Write-Log ("  Skipping {0} unmapped library/libraries: {1}" -f `
            $skippedLibraries.Count, ($skippedLibraries.title -join ', ')) 'DarkGray'
        Write-Log '  Add libraries to $LibraryMap in TrashBoy.config.ps1 to include them.' 'DarkGray'
    }

    if ($FilterLibraries.Count -gt 0) {
        $mappedLibraries = $mappedLibraries | Where-Object { $FilterLibraries -contains $_.title }
        Write-Log ''
        Write-Log ("  Filtered to: {0}" -f ($FilterLibraries -join ', ')) 'Cyan'
    }

    Write-Log ''
    Write-SectionHeader ('SCANNING -- plays <= {0}' -f $effectiveMaxPlays)
    Write-Log ''

    $allUnwatched = [System.Collections.Generic.List[PSObject]]::new()

    foreach ($lib in $mappedLibraries) {
        Write-Log ("  {0}  [{1}]" -f $lib.title, $lib.type) 'White'
        $items = Get-UnwatchedFromLibrary -Library $lib -MaxPlays $effectiveMaxPlays
        $count = $items.Count
        foreach ($i in $items) { $allUnwatched.Add($i) }
        $color = if ($count -gt 0) { 'Yellow' } else { 'Green' }
        Write-Log ("    {0} unwatched item(s) found" -f $count) $color
    }

    $sorted = switch ($ScanConfig.SortBy) {
        'PlayCount' { $allUnwatched | Sort-Object PlayCount, DateAdded }
        'DateAdded' { $allUnwatched | Sort-Object DateAdded }
        'Title'     { $allUnwatched | Sort-Object Title }
        'Size'      { $allUnwatched | Sort-Object SizeBytes -Descending }
        default     { $allUnwatched | Sort-Object PlayCount, DateAdded }
    }

    Write-Log ''
    Write-SectionHeader ('REPORT -- {0} item(s) flagged' -f $sorted.Count)

    if ($sorted.Count -eq 0) {
        Write-Log ''
        Write-Log '  No unwatched media found. Your library is fully watched!' 'Green'
        Write-Log ''
        Write-Log ("  Log saved to: {0}" -f $Script:LogFile) 'Cyan'
        return @()
    }

    $totalBytes = ($sorted | Measure-Object -Property SizeBytes -Sum).Sum
    Write-Log ''
    Write-Log ("  Play data source        : {0}" -f $dataSource) 'DarkGray'
    Write-Log ("  Total reclaimable space : {0}" -f (Format-Bytes $totalBytes)) 'Cyan'
    Write-Log ''

    $grouped = $sorted | Group-Object Library
    foreach ($group in $grouped) {
        $groupBytes = ($group.Group | Measure-Object -Property SizeBytes -Sum).Sum
        Write-Log ("  ┌── {0}" -f $group.Name) 'DarkCyan'
        foreach ($item in $group.Group) {
            $lastStr  = if ($item.LastPlayed) { $item.LastPlayed.ToString('yyyy-MM-dd') } else { 'never    ' }
            $svcLabel = if ($item.Service) { "[{0}]" -f $item.Service } else { '[unmapped]' }
            $yearStr  = if ($item.Year -gt 0) { "({0})" -f $item.Year } else { '      ' }
            $titleFull = '{0} {1}' -f $item.Title, $yearStr
            $color = if ($item.PlayCount -eq 0) { 'White' } else { 'DarkYellow' }
            Write-Log ("  │  {0,-52} Plays:{1,3}  Added:{2:yyyy-MM-dd}  Last:{3}  {4,10}  {5}" -f `
                $titleFull, $item.PlayCount, $item.DateAdded, $lastStr, $item.SizeHuman, $svcLabel) $color
        }
        Write-Log ("  └── {0} item(s)  |  {1}" -f $group.Count, (Format-Bytes $groupBytes)) 'DarkCyan'
        Write-Log ''
    }

    $Script:LastScanResults = [array]$sorted
    return [array]$sorted
}

# ================================================================
#  SHARED: Item list display
#  Used by both the scan report and the pre-delete review
# ================================================================
function Show-ItemList {
    param(
        [array]$Items,
        [string]$Header = 'ITEMS',
        [bool]$WriteToLog = $false,
        [bool]$ShowNumbers = $false
    )

    if (-not $Items -or $Items.Count -eq 0) {
        if ($WriteToLog) { Write-Log '  No items to display.' 'Yellow' }
        else { Write-Host '  No items to display.' -ForegroundColor Yellow }
        return
    }

    $totalBytes = ($Items | Measure-Object -Property SizeBytes -Sum).Sum

    if ($WriteToLog) {
        Write-Log ''
        Write-SectionHeader $Header
        Write-Log ''
        Write-Log ("  Total reclaimable space : {0}" -f (Format-Bytes $totalBytes)) 'Cyan'
        Write-Log ''
    } else {
        Write-Host ''
        Write-Host ('  ' + ('=' * 66)) -ForegroundColor Cyan
        Write-Host ("  {0}" -f $Header) -ForegroundColor Cyan
        Write-Host ('  ' + ('=' * 66)) -ForegroundColor Cyan
        Write-Host ''
        Write-Host ("  Total reclaimable space : {0}" -f (Format-Bytes $totalBytes)) -ForegroundColor Cyan
        Write-Host ''
    }

    $itemNum = 0
    $grouped = $Items | Group-Object Library
    foreach ($group in $grouped) {
        $groupBytes = ($group.Group | Measure-Object -Property SizeBytes -Sum).Sum
        if ($WriteToLog) {
            Write-Log ("  ┌── {0}" -f $group.Name) 'DarkCyan'
        } else {
            Write-Host ("  ┌── {0}" -f $group.Name) -ForegroundColor DarkCyan
        }
        foreach ($item in $group.Group) {
            $itemNum++
            $lastStr   = if ($item.LastPlayed) { $item.LastPlayed.ToString('yyyy-MM-dd') } else { 'never    ' }
            $svcLabel  = if ($item.Service) { "[{0}]" -f $item.Service } else { '[unmapped]' }
            $yearStr   = if ($item.Year -gt 0) { "({0})" -f $item.Year } else { '      ' }
            $titleFull = '{0} {1}' -f $item.Title, $yearStr
            $color     = if ($item.PlayCount -eq 0) { 'White' } else { 'DarkYellow' }
            $numPrefix = if ($ShowNumbers) { "{0,4}. " -f $itemNum } else { '  │  ' }
            $line      = "{0}{1,-52} Plays:{2,3}  Added:{3:yyyy-MM-dd}  Last:{4}  {5,10}  {6}" -f `
                $numPrefix, $titleFull, $item.PlayCount, $item.DateAdded, $lastStr, $item.SizeHuman, $svcLabel
            if ($WriteToLog) { Write-Log $line $color } else { Write-Host $line -ForegroundColor $color }
        }
        $footer = "  └── {0} item(s)  |  {1}" -f $group.Count, (Format-Bytes $groupBytes)
        if ($WriteToLog) { Write-Log $footer 'DarkCyan'; Write-Log '' }
        else { Write-Host $footer -ForegroundColor DarkCyan; Write-Host '' }
    }
}

# ================================================================
#  SHARED: Manual item selection parser
# ================================================================
function Select-ItemsForDeletion {
    param([array]$Items)

    # Display numbered list
    Show-ItemList -Items $Items -Header ('SELECT ITEMS TO DELETE -- {0} available' -f $Items.Count) -ShowNumbers $true

    Write-Host '  Enter item numbers to include, separated by commas.' -ForegroundColor Cyan
    Write-Host '  Ranges are supported (e.g. 1,3,5-8,12). Enter A to select all. Enter M to go back.' -ForegroundColor DarkGray
    Write-Host ''

    do {
        $input = (Read-Host '  Selection').Trim()

        if ($input.ToUpper() -eq 'M') { return $null }
        if ($input.ToUpper() -eq 'A') { return $Items }

        $selectedIndices = [System.Collections.Generic.List[int]]::new()
        $parseError = $false

        foreach ($token in ($input -split ',')) {
            $token = $token.Trim()
            if ($token -match '^(\d+)-(\d+)$') {
                $from = [int]$Matches[1]; $to = [int]$Matches[2]
                if ($from -lt 1 -or $to -gt $Items.Count -or $from -gt $to) {
                    Write-Host ("  Invalid range '{0}' -- valid range is 1-{1}" -f $token, $Items.Count) -ForegroundColor Red
                    $parseError = $true; break
                }
                for ($i = $from; $i -le $to; $i++) { if ($selectedIndices -notcontains $i) { $selectedIndices.Add($i) } }
            } elseif ($token -match '^\d+$') {
                $n = [int]$token
                if ($n -lt 1 -or $n -gt $Items.Count) {
                    Write-Host ("  Invalid number '{0}' -- valid range is 1-{1}" -f $token, $Items.Count) -ForegroundColor Red
                    $parseError = $true; break
                }
                if ($selectedIndices -notcontains $n) { $selectedIndices.Add($n) }
            } else {
                Write-Host ("  Could not parse '{0}' -- use numbers, ranges (e.g. 1-5), or A for all" -f $token) -ForegroundColor Red
                $parseError = $true; break
            }
        }

        if (-not $parseError -and $selectedIndices.Count -gt 0) {
            $selected = @($selectedIndices | Sort-Object | ForEach-Object { $Items[$_ - 1] })
            Write-Host ''
            Write-Host ("  {0} item(s) selected." -f $selected.Count) -ForegroundColor Cyan
            return $selected
        } elseif (-not $parseError) {
            Write-Host '  No items selected. Enter at least one number, or M to go back.' -ForegroundColor Yellow
        }
    } while ($true)
}

# ================================================================
#  DELETE (TOOL 2)
# ================================================================
function Invoke-Delete {
    param([array]$Items, [bool]$WithFiles)

    if (-not $Items -or $Items.Count -eq 0) {
        Write-Log '  No items to delete.' 'Yellow'
        return
    }

    Start-Log 'TrashBoy_Delete'

    $modeLabel = if ($WithFiles) { 'Delete from *arr + delete files' } else { 'Delete from *arr (keep files)' }
    Write-Log ''
    Write-Log '  ============================================================' 'Cyan'
    Write-Log ("   TrashBoy  |  Live Delete -- {0}" -f $modeLabel) 'Cyan'
    Write-Log ('   {0}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')) 'Cyan'
    Write-Log '  ============================================================' 'Cyan'
    Write-Log ''

    $totalBytes = ($Items | Measure-Object -Property SizeBytes -Sum).Sum
    Write-Log ("  Items queued    : {0}" -f $Items.Count) 'White'
    Write-Log ("  Estimated space : {0}" -f (Format-Bytes $totalBytes)) 'White'
    Write-Log ("  Delete files    : {0}" -f $WithFiles) $(if ($WithFiles) { 'Red' } else { 'Yellow' })
    Write-Log ''

    $warningText = if ($WithFiles) {
        "This will remove {0} item(s) from their *arr app AND delete all files from disk." -f $Items.Count
    } else {
        "This will remove {0} item(s) from their *arr app (files will remain on disk)." -f $Items.Count
    }

    if (-not (Confirm-LiveAction $warningText)) { return }

    Write-Log ''
    Write-SectionHeader 'DELETING'
    Write-Log ''

    $deleted = 0; $failed = 0; $skipped = 0
    $deletedItems = [System.Collections.Generic.List[PSObject]]::new()

    foreach ($item in $Items) {
        Write-Log ("  Processing: {0}  [{1}]" -f $item.Title, $item.Library) 'Cyan'

        $ok = $false
        switch ($item.Service) {
            'Radarr' {
                if (-not $Script:ConnectionStatus.Radarr) {
                    Write-Log '    Radarr not connected -- skipped' 'Yellow'; $skipped++; continue
                }
                $ok = Remove-ViaRadarr -Item $item -WithFiles $WithFiles
            }
            'Sonarr' {
                if (-not $Script:ConnectionStatus.Sonarr) {
                    Write-Log '    Sonarr not connected -- skipped' 'Yellow'; $skipped++; continue
                }
                $ok = Remove-ViaSonarr -Item $item -WithFiles $WithFiles
            }
            'Lidarr' {
                if (-not $Script:ConnectionStatus.Lidarr) {
                    Write-Log '    Lidarr not connected -- skipped' 'Yellow'; $skipped++; continue
                }
                $ok = Remove-ViaLidarr -Item $item -WithFiles $WithFiles
            }
            default {
                Write-Log ("    No *arr service mapped for library '{0}' -- skipped" -f $item.Library) 'Yellow'
                $skipped++
                continue
            }
        }

        if ($ok) { $deleted++; $deletedItems.Add($item) } else { $failed++ }
    }

    Write-Log ''
    Write-SectionHeader 'DELETE SUMMARY'
    Write-Log ''
    Write-Log ("  Deleted : {0}  item(s)" -f $deleted) 'Green'
    Write-Log ("  Failed  : {0}  item(s)" -f $failed)  $(if ($failed  -gt 0) { 'Red'    } else { 'Green' })
    Write-Log ("  Skipped : {0}  item(s)" -f $skipped) $(if ($skipped -gt 0) { 'Yellow' } else { 'Green' })

    # ── Plex library rescan ────────────────────────────────────────────────────
    if ($deletedItems.Count -gt 0 -and $WithFiles) {
        $sectionsToRefresh = @($deletedItems |
            ForEach-Object { $_.PlexSectionId } |
            Sort-Object -Unique)

        Write-Log ''
        Write-Log ("  Notifying Plex to rescan {0} library section(s)..." -f $sectionsToRefresh.Count) 'Cyan'

        foreach ($sectionId in $sectionsToRefresh) {
            # Find the library name for display
            $libName = ($deletedItems | Where-Object { $_.PlexSectionId -eq $sectionId } |
                Select-Object -First 1).Library
            try {
                Invoke-PlexApi -Path "/library/sections/$sectionId/refresh" | Out-Null
                Write-Log ("  [RESCAN]   '{0}' (section {1})" -f $libName, $sectionId) 'Green'
            } catch {
                Write-Log ("  [RESCAN FAILED]  '{0}' (section {1}) -- {2}" -f $libName, $sectionId, $_) 'Yellow'
            }
        }
    } elseif ($deletedItems.Count -gt 0 -and -not $WithFiles) {
        Write-Log ''
        Write-Log '  Plex rescan skipped -- files were not deleted, library contents unchanged.' 'DarkGray'
    }
    # ──────────────────────────────────────────────────────────────────────────

    Write-Log ''
    Write-Log ("  Log saved to: {0}" -f $Script:LogFile) 'Cyan'
}

# ================================================================
#  SETTINGS VIEWER (TOOL 3)
# ================================================================
function Show-Settings {
    Write-Log ''
    Write-SectionHeader 'CURRENT SETTINGS'
    Write-Log ''
    Write-Log '  From TrashBoy.config.ps1:' 'DarkGray'
    Write-Log ''
    Write-Log ("  Plex base URL      : {0}" -f $PlexConfig.BaseUrl) 'White'
    Write-Log ''

    if ($TautulliConfig.Enabled) {
        Write-Log ("  Tautulli           : Enabled") 'White'
        Write-Log ("  Tautulli URL       : {0}" -f $TautulliConfig.BaseUrl) 'White'
        Write-Log ("  MinWatchedPercent  : {0}%  (plays below this are not counted)" -f $TautulliConfig.MinWatchedPercent) 'White'
    } else {
        Write-Log '  Tautulli           : Disabled (using Plex viewCount)' 'DarkGray'
    }

    Write-Log ''
    Write-Log ("  Max play count     : {0}  (items with <= this many plays are flagged)" -f $ScanConfig.MaxPlayCount) 'White'
    Write-Log ("  Sort by            : {0}" -f $ScanConfig.SortBy) 'White'
    Write-Log ''

    Write-Log '  *arr Services:' 'DarkGray'
    foreach ($pair in @(
        @{ Name = 'Sonarr'; Cfg = $SonarrConfig }
        @{ Name = 'Radarr'; Cfg = $RadarrConfig }
        @{ Name = 'Lidarr'; Cfg = $LidarrConfig }
    )) {
        $status = if ($pair.Cfg.Enabled) { 'Enabled' } else { 'Disabled' }
        $color  = if ($pair.Cfg.Enabled) { 'White'   } else { 'DarkGray' }
        Write-Log ("  {0,-8}  {1,-10}  {2}" -f $pair.Name, $status, $pair.Cfg.BaseUrl) $color
    }

    Write-Log ''
    Write-Log '  Library Map:' 'DarkGray'
    foreach ($lib in $LibraryMap.Keys | Sort-Object) {
        Write-Log ("  {0,-35} → {1}" -f $lib, $LibraryMap[$lib]) 'White'
    }
    Write-Log ''
    Write-Log '  To change settings, edit TrashBoy.config.ps1 and restart TrashBoy.' 'DarkGray'
    Write-Log ''
}

# ================================================================
#  MAIN MENU
# ================================================================
function Show-MainMenu {
    param($SessionLog)
    Write-Host ''
    Write-Host '  ============================================================' -ForegroundColor Cyan
    Write-Host '   TrashBoy  |  Plex Unwatched Media Cleanup' -ForegroundColor Cyan
    Write-Host '  ============================================================' -ForegroundColor Cyan
    Write-Host ''
    Write-Host '  (1) Scan Libraries    -- find unwatched media and show a report'
    Write-Host '  (2) Delete Unwatched  -- remove flagged items via Sonarr/Radarr/Lidarr'
    Write-Host '  (3) Settings          -- view current configuration'
    Write-Host '  (M) Return to menu    -- (use from any sub-menu)'  -ForegroundColor DarkGray
    Write-Host '  (Q) Quit TrashBoy'                                 -ForegroundColor DarkGray
    Write-Host ''

    # Connection status widget
    Write-Host '  Connections:' -ForegroundColor DarkGray
    $plexColor = if ($Script:ConnectionStatus.Plex) { 'Green' } else { 'Red' }
    Write-Host ("    {0,-10}  {1}" -f 'Plex', $(if ($Script:ConnectionStatus.Plex) { 'OK' } else { 'UNREACHABLE' })) -ForegroundColor $plexColor

    if ($TautulliConfig.Enabled) {
        $tColor = if ($Script:ConnectionStatus.Tautulli) { 'Green' } else { 'Red' }
        $tLabel = if ($Script:ConnectionStatus.Tautulli) {
            "OK  (play source: Tautulli, min {0}% watched)" -f $TautulliConfig.MinWatchedPercent
        } else {
            'UNREACHABLE  (falling back to Plex viewCount)'
        }
        Write-Host ("    {0,-10}  {1}" -f 'Tautulli', $tLabel) -ForegroundColor $tColor
    } else {
        Write-Host ("    {0,-10}  Disabled  (play source: Plex viewCount)" -f 'Tautulli') -ForegroundColor DarkGray
    }

    foreach ($pair in @(
        @{ Name = 'Sonarr'; Cfg = $SonarrConfig; Key = 'Sonarr' }
        @{ Name = 'Radarr'; Cfg = $RadarrConfig; Key = 'Radarr' }
        @{ Name = 'Lidarr'; Cfg = $LidarrConfig; Key = 'Lidarr' }
    )) {
        if (-not $pair.Cfg.Enabled) {
            Write-Host ("    {0,-10}  Disabled" -f $pair.Name) -ForegroundColor DarkGray
        } else {
            $ok    = $Script:ConnectionStatus[$pair.Key]
            $color = if ($ok) { 'Green' } else { 'Red' }
            Write-Host ("    {0,-10}  {1}" -f $pair.Name, $(if ($ok) { 'OK' } else { 'UNREACHABLE' })) -ForegroundColor $color
        }
    }

    if ($Script:LastScanResults -ne $null) {
        Write-Host ''
        $reclaimable = Format-Bytes (($Script:LastScanResults | Measure-Object -Property SizeBytes -Sum).Sum)
        Write-Host ("  Last scan: {0} item(s) flagged, {1} reclaimable" -f `
            $Script:LastScanResults.Count, $reclaimable) `
            -ForegroundColor $(if ($Script:LastScanResults.Count -gt 0) { 'Yellow' } else { 'Green' })
    }

    Write-Host ''

    if ($SessionLog.Count -gt 0) {
        Write-Host '  This session:' -ForegroundColor DarkGray
        foreach ($entry in $SessionLog) {
            Write-Host ("    {0}" -f $entry) -ForegroundColor DarkGray
        }
        Write-Host ''
    }
}

# ================================================================
#  ENTRY POINT
# ================================================================
$SessionLog             = [System.Collections.Generic.List[string]]::new()
$Script:QuitRequested   = $false
$Script:ReturnedToMenu  = $false
$Script:ToolStartTime   = $null
$Script:LastScanResults = $null

function Add-SessionEntry ([string]$Entry) {
    $time = Get-Date -Format 'HH:mm'
    if ($Script:ToolStartTime) {
        $elapsed = (Get-Date) - $Script:ToolStartTime
        $elapsedStr = if ($elapsed.TotalMinutes -ge 1) {
            '{0}m {1}s' -f [int]$elapsed.TotalMinutes, $elapsed.Seconds
        } else {
            '{0}s' -f [int]$elapsed.TotalSeconds
        }
        $SessionLog.Add(("[{0}] {1}  ({2})" -f $time, $Entry, $elapsedStr))
    } else {
        $SessionLog.Add(("[{0}] {1}" -f $time, $Entry))
    }
    $Script:ToolStartTime = $null
}

do {
    Show-MainMenu $SessionLog
    do { $menuChoice = (Read-Host '  Choice').ToUpper() } until ($menuChoice -in '1','2','3','M','Q')

    if ($menuChoice -eq 'Q') { $Script:QuitRequested = $true; break }
    if ($menuChoice -eq 'M') { continue }

    switch ($menuChoice) {

        '1' {
            $Script:ToolStartTime = Get-Date

            $allLibraries    = Get-PlexLibraries
            $mappedLibraries = @($allLibraries | Where-Object { $LibraryMap.ContainsKey($_.title) })
            $libNames        = @($mappedLibraries | ForEach-Object { $_.title })

            $scopeOptions = @('All libraries') + $libNames
            $scopeChoice  = Select-SubMode 'Select scan scope:' $scopeOptions -Title 'Scan Libraries'
            if ($scopeChoice -eq  0) { $Script:ReturnedToMenu = $true; break }
            if ($scopeChoice -eq -1) { $Script:QuitRequested  = $true; break }

            $filterLibs = @()
            if ($scopeChoice -gt 1) {
                $filterLibs = @($libNames[$scopeChoice - 2])
            }

            $results    = Invoke-UnwatchedScan -FilterLibraries $filterLibs
            $scopeLabel = if ($filterLibs.Count -gt 0) { $filterLibs -join ', ' } else { 'All' }
            Add-SessionEntry ("Scan [{0}] -- {1} item(s) flagged" -f $scopeLabel, $(if ($results) { $results.Count } else { 0 }))
        }

        '2' {
            if (-not $Script:LastScanResults -or $Script:LastScanResults.Count -eq 0) {
                Write-Host ''
                Write-Host '  No scan results available. Run a Scan first (option 1).' -ForegroundColor Yellow
                Write-Host ''
                $Script:ReturnedToMenu = $true; break
            }

            $Script:ToolStartTime = Get-Date

            # ── Step 1: choose scope ──────────────────────────────────────────
            $deleteScope = Select-SubMode 'Select scope -- you will review items and confirm before anything is deleted:' @(
                ("All libraries  -- {0} item(s) flagged" -f $Script:LastScanResults.Count)
                'Choose a specific library'
            ) -Title 'Delete Unwatched'
            if ($deleteScope -eq  0) { $Script:ReturnedToMenu = $true; break }
            if ($deleteScope -eq -1) { $Script:QuitRequested  = $true; break }

            $itemsToDelete = $Script:LastScanResults
            $selectedLib   = 'All'

            if ($deleteScope -eq 2) {
                $groupNames   = @($Script:LastScanResults | Group-Object Library | ForEach-Object { $_.Name })
                $libChoice    = Select-SubMode 'Select library:' $groupNames -Title 'Delete Unwatched  >  Choose Library'
                if ($libChoice -eq  0) { $Script:ReturnedToMenu = $true; break }
                if ($libChoice -eq -1) { $Script:QuitRequested  = $true; break }
                $selectedLib   = $groupNames[$libChoice - 1]
                $itemsToDelete = @($Script:LastScanResults | Where-Object { $_.Library -eq $selectedLib })
            }

            # ── Step 2: show what would be deleted ───────────────────────────
            $scopeLabel = if ($selectedLib -eq 'All') {
                'All libraries -- {0} item(s)' -f $itemsToDelete.Count
            } else {
                '{0} -- {1} item(s)' -f $selectedLib, $itemsToDelete.Count
            }
            Show-ItemList -Items $itemsToDelete -Header ("FLAGGED ITEMS -- {0}" -f $scopeLabel)

            Write-Host '  You will be asked to type YES before anything is deleted.' -ForegroundColor DarkGray
            Write-Host ''

            # ── Step 3: selection mode ────────────────────────────────────────
            $selectionMode = Select-SubMode 'Select items to delete:' @(
                ("All {0} item(s) listed above" -f $itemsToDelete.Count)
                'Manually select items by number'
            ) -Title 'Delete Unwatched'
            if ($selectionMode -eq  0) { $Script:ReturnedToMenu = $true; break }
            if ($selectionMode -eq -1) { $Script:QuitRequested  = $true; break }

            if ($selectionMode -eq 2) {
                $itemsToDelete = Select-ItemsForDeletion -Items $itemsToDelete
                if ($null -eq $itemsToDelete) { $Script:ReturnedToMenu = $true; break }
            }

            # ── Step 4: choose mode ───────────────────────────────────────────
            $modeChoice = Select-SubMode 'Select delete mode:' @(
                'Remove from *arr only  -- item removed from app, files stay on disk'
                'Remove from *arr + delete files  -- PERMANENT, files gone from disk'
            ) -Title 'Delete Unwatched'
            if ($modeChoice -eq  0) { $Script:ReturnedToMenu = $true; break }
            if ($modeChoice -eq -1) { $Script:QuitRequested  = $true; break }

            $withFiles = ($modeChoice -eq 2)
            Invoke-Delete -Items $itemsToDelete -WithFiles $withFiles

            $modeStr = if ($withFiles) { 'with files' } else { 'keep files' }
            Add-SessionEntry ("Delete [{0}] [{1}] -- {2} item(s)" -f $modeStr, $selectedLib, $itemsToDelete.Count)
        }

        '3' {
            Show-Settings
            $Script:ReturnedToMenu = $true
        }
    }

    if ($Script:QuitRequested) { break }

    if (-not $Script:ReturnedToMenu) {
        Write-Host ''
        Write-Host '  Press M for main menu, or any other key to continue...' -ForegroundColor DarkGray
        $key = $Host.UI.RawUI.ReadKey('NoEcho,IncludeKeyDown')
        if ($key.Character -eq 'M' -or $key.Character -eq 'm') { }
    }
    $Script:ReturnedToMenu = $false

} while (-not $Script:QuitRequested)

Write-Host ''
Write-Host '  All done. Thanks for using TrashBoy -- enjoy the reclaimed space!' -ForegroundColor Cyan
Write-Host ''
