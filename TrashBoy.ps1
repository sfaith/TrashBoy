$Script:ConnectionStatus = @{
    Plex     = $false
    Tautulli = $false
    Sonarr   = $false
    Radarr   = $false
    Lidarr   = $false
}

function Invoke-ConnectionCheck {
    Write-Host ''
    Write-Host '  ============================================================' -ForegroundColor Cyan
    Write-Host '   TrashBoy  |  Connection Check' -ForegroundColor Cyan
    Write-Host '  ============================================================' -ForegroundColor Cyan
    Write-Host ''

    # Plex
    $plexStatus = Invoke-PlexApi -Path '/identity'
    if ($plexStatus) {
        $Script:ConnectionStatus.Plex = $true
        Write-Host ("  {0,-10}  [OK]  {1}" -f 'Plex', $PlexConfig.BaseUrl) -ForegroundColor Green
    } else {
        Write-Host ("  {0,-10}  [FAIL]  Cannot reach {1}" -f 'Plex', $PlexConfig.BaseUrl) -ForegroundColor Red
    }

    # Tautulli
    if ($TautulliConfig.Enabled) {
        $tautulliStatus = Invoke-TautulliApi -Command 'get_server_info'
        if ($tautulliStatus) {
            $Script:ConnectionStatus.Tautulli = $true
            Write-Host ("  {0,-10}  [OK]  {1}  (MinWatchedPercent: {2}%)" -f `
                'Tautulli', $TautulliConfig.BaseUrl, $TautulliConfig.MinWatchedPercent) -ForegroundColor Green
        } else {
            Write-Host ("  {0,-10}  [FAIL]  Cannot reach {1}" -f 'Tautulli', $TautulliConfig.BaseUrl) -ForegroundColor Red
            Write-Host ("  {0,-10}  Will fall back to Plex viewCount for play data." -f '') -ForegroundColor Yellow
        }
    } else {
        Write-Host ("  {0,-10}  Disabled -- using Plex viewCount as play source" -f 'Tautulli') -ForegroundColor DarkGray
    }

    # *arr apps
    foreach ($pair in @(
        @{ Name = 'Sonarr'; Config = $SonarrConfig; Key = 'Sonarr' }
        @{ Name = 'Radarr'; Config = $RadarrConfig; Key = 'Radarr' }
        @{ Name = 'Lidarr'; Config = $LidarrConfig; Key = 'Lidarr' }
    )) {
        if (-not $pair.Config.Enabled) {
            Write-Host ("  {0,-10}  Disabled" -f $pair.Name) -ForegroundColor DarkGray
            continue
        }
        $status = Invoke-ArrGet $pair.Config 'system/status'
        if ($status) {
            $Script:ConnectionStatus[$pair.Key] = $true
            Write-Host ("  {0,-10}  [OK]  v{1}" -f $pair.Name, $status.version) -ForegroundColor Green
        } else {
            Write-Host ("  {0,-10}  [FAIL]  Cannot reach {1}" -f $pair.Name, $pair.Config.BaseUrl) -ForegroundColor Red
        }
    }

    Write-Host ''
    if (-not $Script:ConnectionStatus.Plex) {
        Write-Host '  [WARN] Plex is unreachable. TrashBoy cannot scan without Plex.' -ForegroundColor Red
        Write-Host '  Check PlexConfig.BaseUrl and PlexConfig.Token in TrashBoy.config.ps1.' -ForegroundColor Yellow
    }
    Write-Host ''
}

