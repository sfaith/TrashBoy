#
#  Identifies unwatched or rarely watched media across your Plex
#  libraries and optionally removes it via Sonarr, Radarr, or Lidarr.
#
#  QUICK START:
#    1. Copy TrashBoy.config.example.ps1 to TrashBoy.config.ps1
#    2. Edit TrashBoy.config.ps1 with your settings
#    3. Run: .\TrashBoy.ps1  (or double-click TrashBoy.bat)
#
#  HOW TO FIND YOUR PLEX TOKEN:
#    1. Open Plex Web in a browser and sign in
#    2. Browse to any library item, click (...) > Get Info > View XML
