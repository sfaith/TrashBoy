function Invoke-ArrGet ([hashtable]$Config, [string]$Endpoint) {
    $uri = "$($Config.BaseUrl.TrimEnd('/'))/api/$($Config.ApiVersion)/$Endpoint"
    try {
        return Invoke-RestMethod -Uri $uri -Headers @{ 'X-Api-Key' = $Config.ApiKey } -Method Get -ErrorAction Stop
    } catch {
        Write-Log ("  [ERROR] GET {0} -- {1}" -f $uri, $_) 'Red'
        return $null
    }
}

function Invoke-ArrDelete ([hashtable]$Config, [string]$Endpoint) {
    $uri = "$($Config.BaseUrl.TrimEnd('/'))/api/$($Config.ApiVersion)/$Endpoint"
