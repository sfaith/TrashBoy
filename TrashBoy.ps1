function Get-ItemSizeBytes ([object]$MediaNode) {
    $total = [long]0
    if ($MediaNode.PSObject.Properties['Media'] -and $MediaNode.Media) {
        foreach ($m in $MediaNode.Media) {
            if ($m.PSObject.Properties['Part'] -and $m.Part) {
                foreach ($p in $m.Part) {
                    if ($p.PSObject.Properties['size'] -and $p.size) { $total += [long]$p.size }
                }
            }
        }
    }
    return $total
}

function Get-GuidValue ([object]$Item, [string]$Scheme) {
    if ($Item.PSObject.Properties['Guid'] -and $Item.Guid) {
        $hit = $Item.Guid | Where-Object { $_.PSObject.Properties['id'] -and $_.id -like "$Scheme`://*" } | Select-Object -First 1
        if ($hit) { return ($hit.id -replace "$Scheme`://", '') }
    }
    return ''
}

function Get-UnwatchedFromLibrary {
    param([PSObject]$Library, [int]$MaxPlays)

    $libKey   = $Library.key        # Plex section id
    $libName  = $Library.title
    $libType  = $Library.type       # movie | show | artist | photo
    $service  = if ($LibraryMap.ContainsKey($libName)) { $LibraryMap[$libName] } else { $null }
    $results  = [System.Collections.Generic.List[PSObject]]::new()

    switch ($libType) {

        # ── MOVIES ────────────────────────────────────────────────────────────
        'movie' {
            $data = Invoke-PlexApi -Path "/library/sections/$libKey/all"
            if (-not $data) { return $results }
            $items = $data.MediaContainer.Metadata
            if (-not $items) { return $results }

            $idx = 0
            foreach ($item in $items) {
                $idx++
                Write-Progress2 'Scanning movies...' $idx $items.Count $item.title

                $plexViews    = if ($item.PSObject.Properties['viewCount'])    { [int]$item.viewCount }    else { 0 }
                $plexLastView = if ($item.PSObject.Properties['lastViewedAt']) {
                    [DateTimeOffset]::FromUnixTimeSeconds([long]$item.lastViewedAt).LocalDateTime
                } else { $null }

                $playInfo = Get-PlayInfo `
                    -RatingKey      $item.ratingKey `
                    -SectionId      $libKey `
                    -LibraryType    'movie' `
                    -PlexViewCount  $plexViews `
                    -PlexLastViewed $plexLastView

                if ($playInfo.PlayCount -gt $MaxPlays) { continue }

                $addedAt   = [DateTimeOffset]::FromUnixTimeSeconds([long]$item.addedAt).LocalDateTime
                $sizeBytes = Get-ItemSizeBytes $item

                $results.Add([PSCustomObject]@{
                    Library       = $libName
                    Type          = 'Movie'
                    Title         = $item.title
                    Year          = if ($item.PSObject.Properties['year']) { [int]$item.year } else { 0 }
                    PlayCount     = $playInfo.PlayCount
                    LastPlayed    = $playInfo.LastPlayed
                    DateAdded     = $addedAt
                    DaysOld       = ([DateTime]::Now - $addedAt).Days
                    SizeBytes     = $sizeBytes
                    SizeHuman     = Format-Bytes $sizeBytes
                    GuidTmdb      = Get-GuidValue $item 'tmdb'
                    GuidImdb      = Get-GuidValue $item 'imdb'
                    GuidTvdb      = ''
                    GuidMbrainz   = ''
                    Service       = $service
                    PlexKey       = $item.ratingKey
                    PlexSectionId = $libKey
                })
            }
            Clear-Progress
        }

        # ── TV SHOWS ──────────────────────────────────────────────────────────
        'show' {
            $data = Invoke-PlexApi -Path "/library/sections/$libKey/all"
            if (-not $data) { return $results }
            $shows = $data.MediaContainer.Metadata
            if (-not $shows) { return $results }

            $idx = 0
            foreach ($show in $shows) {
                $idx++
                Write-Progress2 'Scanning shows...' $idx $shows.Count $show.title

                # For Tautulli: use show-level play count (aggregate across episodes)
                # For Plex: scan episodes individually to get max play count
                $plexShowViews    = if ($show.PSObject.Properties['viewCount'])    { [int]$show.viewCount }    else { 0 }
                $plexShowLastView = if ($show.PSObject.Properties['lastViewedAt']) {
                    [DateTimeOffset]::FromUnixTimeSeconds([long]$show.lastViewedAt).LocalDateTime
                } else { $null }

                $playInfo = Get-PlayInfo `
                    -RatingKey      $show.ratingKey `
                    -SectionId      $libKey `
                    -LibraryType    'show' `
                    -PlexViewCount  $plexShowViews `
                    -PlexLastViewed $plexShowLastView

                # Plex fallback needs episode-level check
                if (-not ($TautulliConfig.Enabled -and $Script:ConnectionStatus.Tautulli)) {
                    $epData   = Invoke-PlexApi -Path "/library/metadata/$($show.ratingKey)/allLeaves"
                    $episodes = if ($epData -and $epData.PSObject.Properties['MediaContainer'] -and $epData.MediaContainer.PSObject.Properties['Metadata']) {
                        $epData.MediaContainer.Metadata
                    } else { @() }
                    $maxEpViews = 0
                    foreach ($ep in $episodes) {
                        $v = if ($ep.PSObject.Properties['viewCount']) { [int]$ep.viewCount } else { 0 }
                        if ($v -gt $maxEpViews) { $maxEpViews = $v }
                    }
                    $playInfo.PlayCount = $maxEpViews
                }

                if ($playInfo.PlayCount -gt $MaxPlays) { continue }

                # Compute size from episodes
                $totalSize = [long]0
                $epData2 = Invoke-PlexApi -Path "/library/metadata/$($show.ratingKey)/allLeaves"
                if ($epData2 -and $epData2.PSObject.Properties['MediaContainer'] -and $epData2.MediaContainer.PSObject.Properties['Metadata'] -and $epData2.MediaContainer.Metadata) {
                    foreach ($ep in $epData2.MediaContainer.Metadata) {
                        $totalSize += Get-ItemSizeBytes $ep
                    }
                }

                $addedAt = [DateTimeOffset]::FromUnixTimeSeconds([long]$show.addedAt).LocalDateTime

                $results.Add([PSCustomObject]@{
                    Library       = $libName
                    Type          = 'TVShow'
                    Title         = $show.title
                    Year          = if ($show.PSObject.Properties['year']) { [int]$show.year } else { 0 }
                    PlayCount     = $playInfo.PlayCount
                    LastPlayed    = $playInfo.LastPlayed
                    DateAdded     = $addedAt
                    DaysOld       = ([DateTime]::Now - $addedAt).Days
                    SizeBytes     = $totalSize
                    SizeHuman     = Format-Bytes $totalSize
                    GuidTmdb      = ''
                    GuidImdb      = Get-GuidValue $show 'imdb'
                    GuidTvdb      = Get-GuidValue $show 'tvdb'
                    GuidMbrainz   = ''
                    Service       = $service
                    PlexKey       = $show.ratingKey
                    PlexSectionId = $libKey
                })
            }
            Clear-Progress
        }

        # ── MUSIC ─────────────────────────────────────────────────────────────
        'artist' {
            $data = Invoke-PlexApi -Path "/library/sections/$libKey/all"
            if (-not $data) { return $results }
            $artists = $data.MediaContainer.Metadata
            if (-not $artists) { return $results }

            $idx = 0
            foreach ($artist in $artists) {
                $idx++
                Write-Progress2 'Scanning artists...' $idx $artists.Count $artist.title

                $plexViews    = if ($artist.PSObject.Properties['viewCount']) { [int]$artist.viewCount } else { 0 }
                $plexLastView = $null

                $playInfo = Get-PlayInfo `
                    -RatingKey      $artist.ratingKey `
                    -SectionId      $libKey `
                    -LibraryType    'artist' `
                    -PlexViewCount  $plexViews `
                    -PlexLastViewed $plexLastView

                # Plex fallback: scan tracks
                if (-not ($TautulliConfig.Enabled -and $Script:ConnectionStatus.Tautulli)) {
                    $trackData = Invoke-PlexApi -Path "/library/metadata/$($artist.ratingKey)/allLeaves"
                    $tracks    = if ($trackData -and $trackData.PSObject.Properties['MediaContainer'] -and $trackData.MediaContainer.PSObject.Properties['Metadata']) {
                        $trackData.MediaContainer.Metadata
                    } else { @() }
                    $maxTrackViews = 0
                    foreach ($t in $tracks) {
                        $v = if ($t.PSObject.Properties['viewCount']) { [int]$t.viewCount } else { 0 }
                        if ($v -gt $maxTrackViews) { $maxTrackViews = $v }
                    }
                    $playInfo.PlayCount = $maxTrackViews
                }

                if ($playInfo.PlayCount -gt $MaxPlays) { continue }

                # Compute size from tracks
                $totalSize = [long]0
                $trackData2 = Invoke-PlexApi -Path "/library/metadata/$($artist.ratingKey)/allLeaves"
                if ($trackData2 -and $trackData2.PSObject.Properties['MediaContainer'] -and $trackData2.MediaContainer.PSObject.Properties['Metadata'] -and $trackData2.MediaContainer.Metadata) {
                    foreach ($t in $trackData2.MediaContainer.Metadata) {
                        $totalSize += Get-ItemSizeBytes $t
                    }
                }

                $addedAt = [DateTimeOffset]::FromUnixTimeSeconds([long]$artist.addedAt).LocalDateTime

                $results.Add([PSCustomObject]@{
                    Library       = $libName
                    Type          = 'Artist'
                    Title         = $artist.title
                    Year          = 0
                    PlayCount     = $playInfo.PlayCount
                    LastPlayed    = $playInfo.LastPlayed
                    DateAdded     = $addedAt
                    DaysOld       = ([DateTime]::Now - $addedAt).Days
                    SizeBytes     = $totalSize
                    SizeHuman     = Format-Bytes $totalSize
                    GuidTmdb      = ''
                    GuidImdb      = ''
                    GuidTvdb      = ''
                    GuidMbrainz   = Get-GuidValue $artist 'musicbrainz'
                    Service       = $service
                    PlexKey       = $artist.ratingKey
                    PlexSectionId = $libKey
                })
            }
            Clear-Progress
        }

        default { }  # photo libraries etc -- silently skip
    }

    return $results
}

# ================================================================
