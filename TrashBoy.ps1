# ================================================================
#  PLAY DATA: unified source (Tautulli or Plex)
# ================================================================

# Returns: @{ PlayCount = int; LastPlayed = DateTime|null }
# Source is Tautulli when enabled and connected, Plex viewCount otherwise.
# For Tautulli movie plays, applies MinWatchedPercent via get_history.
# For Tautulli TV/music, uses show/artist-level play_count from get_library_media_info.
$Script:TautulliCache = @{}   # section_id -> hashtable of rating_key -> play data

function Get-TautulliSectionCache ([string]$SectionId, [string]$LibraryType) {
    if (-not $Script:TautulliCache.ContainsKey($SectionId)) {
        Clear-Progress
        Write-Host ("  Loading Tautulli play data for section {0}..." -f $SectionId) -ForegroundColor DarkGray
        $Script:TautulliCache[$SectionId] = Get-TautulliPlayData -SectionId $SectionId -LibraryType $LibraryType
        Write-Host ("    {0} item(s) loaded from Tautulli." -f $Script:TautulliCache[$SectionId].Count) -ForegroundColor DarkGray
    }
    return $Script:TautulliCache[$SectionId]
}

function Get-PlayInfo ([string]$RatingKey, [string]$SectionId, [string]$LibraryType, [int]$PlexViewCount, [nullable[DateTime]]$PlexLastViewed) {
    # Returns [int]$PlayCount, [DateTime|null]$LastPlayed

    $useTautulli = $TautulliConfig.Enabled -and $Script:ConnectionStatus.Tautulli

    if ($useTautulli) {
        $cache = Get-TautulliSectionCache -SectionId $SectionId -LibraryType $LibraryType
        if ($cache.ContainsKey($RatingKey)) {
            $entry = $cache[$RatingKey]
            $rawCount = [int]$entry.PlayCount

            # For movies: validate against MinWatchedPercent via history
            # For shows/artists: trust the aggregate count from get_library_media_info
            if ($LibraryType -eq 'movie' -and $rawCount -gt 0 -and $TautulliConfig.MinWatchedPercent -gt 0) {
                $qualifying = Get-TautulliHistoryPlayCount -RatingKey $RatingKey -MediaType $LibraryType
                return @{ PlayCount = $qualifying; LastPlayed = $entry.LastPlayed }
            }
            return @{ PlayCount = $rawCount; LastPlayed = $entry.LastPlayed }
        }
        # Item not in Tautulli (never played) -- treat as 0
        return @{ PlayCount = 0; LastPlayed = $null }
    }

    # Plex fallback
    return @{ PlayCount = $PlexViewCount; LastPlayed = $PlexLastViewed }
}

