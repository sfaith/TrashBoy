#
#    Plex only (fallback):
#      When Tautulli is disabled, TrashBoy uses Plex's built-in
#      viewCount, which only reflects the server owner's account
#      and has no completion threshold.
#
#  HOW IT WORKS:
#    TV shows  : evaluated at series level. If any episode has been
#                played (above MinWatchedPercent) the series is excluded.
#    Music     : evaluated at artist level. If any track has been played
#                the artist is excluded.
#    Deletion  : always routed through the appropriate *arr app.
#                TrashBoy never deletes files directly.
#
#  REQUIREMENTS:
#    - PowerShell 5.1 or later
#    - TrashBoy.config.ps1 in the same folder as this script
