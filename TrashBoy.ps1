$Script:LogFile = $null

function Start-Log ([string]$Prefix) {
    $logDir = Join-Path $PSScriptRoot 'Logs'
    if (-not (Test-Path -LiteralPath $logDir)) {
        New-Item -ItemType Directory -Path $logDir -Force | Out-Null
    }
    $Script:LogFile = Join-Path $logDir ("{0}_{1}.log" -f $Prefix, (Get-Date -Format 'yyyyMMdd_HHmmss'))
}

function Write-Log {
    param([string]$Message, [string]$Color = 'White')
    Write-Host $Message -ForegroundColor $Color
    if ($Script:LogFile) {
        $Message | Out-File $Script:LogFile -Append -Encoding utf8
    }
}

function Write-SectionHeader ([string]$Title) {
    Write-Log ''
    Write-Log ('  ' + ('=' * 66)) 'Cyan'
    Write-Log ("  $Title") 'Cyan'
    Write-Log ('  ' + ('=' * 66)) 'Cyan'
}

function Write-Progress2 ([string]$Label, [int]$Current, [int]$Total, [string]$Item = '') {
    $truncated = if ($Item.Length -gt 50) { $Item.Substring(0, 47) + '...' } else { $Item }
    $line = '  {0} {1} / {2}  ({3})' -f $Label, $Current, $Total, $truncated
    Write-Host ("`r{0,-90}" -f $line) -NoNewline -ForegroundColor DarkGray
}

function Clear-Progress {
    Write-Host ("`r{0}" -f (' ' * 90)) -NoNewline
    Write-Host "`r" -NoNewline
}

function Format-Bytes ([long]$Bytes) {
    if ($Bytes -ge 1TB) { return ('{0:N2} TB' -f ($Bytes / 1TB)) }
    if ($Bytes -ge 1GB) { return ('{0:N2} GB' -f ($Bytes / 1GB)) }
    if ($Bytes -ge 1MB) { return ('{0:N1} MB' -f ($Bytes / 1MB)) }
    return ('{0} B' -f $Bytes)
}

