function Invoke-TautulliApi ([string]$Command, [hashtable]$Params = @{}) {
    $uri = "$($TautulliConfig.BaseUrl.TrimEnd('/'))/api/v2?apikey=$($TautulliConfig.ApiKey)&cmd=$Command"
    foreach ($k in $Params.Keys) {
        $uri += "&$k=$([Uri]::EscapeDataString($Params[$k].ToString()))"
    }
    try {
        $response = Invoke-RestMethod -Uri $uri -Method Get -ErrorAction Stop
        if ($response.response.result -eq 'success') {
            return $response.response.data
        } else {
            Write-Log ("  [ERROR] Tautulli {0} -- {1}" -f $Command, $response.response.message) 'Red'
            return $null
        }
    } catch {
        Write-Log ("  [ERROR] Tautulli API {0} -- {1}" -f $Command, $_) 'Red'
        return $null
    }
}

# Build a hashtable of rating_key -> qualifying play count from Tautulli
# Uses get_library_media_info which returns play_count and last_played per item
# Paginates automatically since large libraries may exceed the default page size.
function Get-TautulliPlayData ([string]$SectionId, [string]$LibraryType) {
    $playData   = @{}   # rating_key (string) -> @{ PlayCount = int; LastPlayed = DateTime|null }
    $pageSize   = 1000
    $start      = 0
    $totalItems = $null

    do {
        $params = @{
            section_id   = $SectionId
            length       = $pageSize
            start        = $start
            order_column = 'added_at'
            order_dir    = 'asc'
        }

        $page = Invoke-TautulliApi -Command 'get_library_media_info' -Params $params
        if (-not $page) { break }

        if ($null -eq $totalItems) {
            $totalItems = [int]$page.recordsTotal
        }

        $rows = $page.data
        if (-not $rows -or $rows.Count -eq 0) { break }

        foreach ($row in $rows) {
            $ratingKey = $row.rating_key.ToString()
            $rawCount  = if ($row.play_count) { [int]$row.play_count } else { 0 }
            $lastPlayed = $null
            if ($row.last_played -and [long]$row.last_played -gt 0) {
                $lastPlayed = [DateTimeOffset]::FromUnixTimeSeconds([long]$row.last_played).LocalDateTime
            }
            $playData[$ratingKey] = @{ PlayCount = $rawCount; LastPlayed = $lastPlayed }
        }

        $start += $rows.Count
    } while ($start -lt $totalItems)

    return $playData
}

# For TV shows: Tautulli's get_library_media_info at the show level returns
# aggregate play counts across all episodes. We use grandparent_rating_key
# matching via get_history to check per-episode completion, but that is
# expensive at scale. Instead we use the show-level play_count from
# get_library_media_info (section_type=show returns show rows), and trust
# that a show with play_count > 0 means at least one episode was watched.
# The MinWatchedPercent check is applied at the history level for movies;
# for shows we accept the show-level count and let the threshold filter.

function Get-TautulliHistoryPlayCount ([string]$RatingKey, [string]$MediaType) {
    # Returns the count of history entries for this item that meet MinWatchedPercent.
    # Used to validate movie play counts against the completion threshold.
    $minPct  = [int]$TautulliConfig.MinWatchedPercent
    $start   = 0
    $pgSize  = 100
    $qualifying = 0
    $total   = $null

    do {
        $params = @{
            rating_key = $RatingKey
            length     = $pgSize
            start      = $start
        }
        $page = Invoke-TautulliApi -Command 'get_history' -Params $params
        if (-not $page) { break }

        if ($null -eq $total) { $total = [int]$page.recordsTotal }
        $rows = $page.data
        if (-not $rows -or $rows.Count -eq 0) { break }

        foreach ($row in $rows) {
            $pct = if ($row.percent_complete) { [int]$row.percent_complete } else { 0 }
            if ($pct -ge $minPct) { $qualifying++ }
        }
        $start += $rows.Count
    } while ($start -lt $total)

    return $qualifying
}

