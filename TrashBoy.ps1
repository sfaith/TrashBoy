        Invoke-RestMethod -Uri $uri -Headers @{ 'X-Api-Key' = $Config.ApiKey } -Method Delete -ErrorAction Stop | Out-Null
        return $true
    } catch {
        Write-Log ("  [ERROR] DELETE {0} -- {1}" -f $uri, $_) 'Red'
        return $false
    }
}

