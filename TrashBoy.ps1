# ================================================================
function Remove-ViaRadarr ([PSObject]$Item, [bool]$WithFiles) {
    $movies = Invoke-ArrGet $RadarrConfig 'movie'
    if (-not $movies) { return $false }

    $match = $null
    if ($Item.GuidTmdb) {
        $tmdbId = try { [int]$Item.GuidTmdb } catch { 0 }
        if ($tmdbId) { $match = $movies | Where-Object { $_.tmdbId -eq $tmdbId } | Select-Object -First 1 }
    }
    if (-not $match -and $Item.GuidImdb) {
        $match = $movies | Where-Object { $_.imdbId -eq $Item.GuidImdb } | Select-Object -First 1
    }
    if (-not $match) {
        $match = $movies | Where-Object { $_.title -eq $Item.Title } | Select-Object -First 1
    }
    if (-not $match) {
        Write-Log ("  [NO MATCH] Radarr has no record of '{0}' -- skipped" -f $Item.Title) 'Yellow'
        return $false
    }

    $deleteFlag = $WithFiles.ToString().ToLower()
    $ok = Invoke-ArrDelete $RadarrConfig "movie/$($match.id)?deleteFiles=$deleteFlag&addImportExclusion=false"
    if ($ok) { Write-Log ("  [DELETED]  [Radarr] {0}" -f $Item.Title) 'Green' }
    return $ok
}

